-- Persistent, auditable monitoring pipeline. All timestamps are stored in UTC.
create table if not exists public.search_queries (
  id bigint generated by default as identity primary key,
  query_text text not null unique,
  weight integer not null default 10,
  active boolean not null default true,
  provider_options jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.search_queries(query_text, weight, active)
select term, weight, active = 1 from public.search_terms
on conflict (query_text) do update set weight=excluded.weight, active=excluded.active;

