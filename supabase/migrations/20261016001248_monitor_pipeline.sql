create table if not exists public.monitor_runs (
  id bigint generated by default as identity primary key,
  trigger_type text not null check (trigger_type in ('cron','manual','backfill','test')),
  status text not null default 'running' check (status in ('running','success','partial','failed','skipped_locked')),
  window_start timestamptz not null,
  window_end timestamptz not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  queries_total integer not null default 0,
  candidates_total integer not null default 0,
  candidates_new integer not null default 0,
  news_new integer not null default 0,
  errors_total integer not null default 0,
  message text,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.query_runs (
  id bigint generated by default as identity primary key,
  monitor_run_id bigint not null references public.monitor_runs(id) on delete cascade,
  search_query_id bigint references public.search_queries(id) on delete set null,
  source_id integer references public.sources(id) on delete set null,
  provider text not null,
  query_text text,
  status text not null check (status in ('success','error','skipped')),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  results_count integer not null default 0,
  new_candidates_count integer not null default 0,
  error_message text,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.candidate_news (
  id bigint generated by default as identity primary key,
  provider text not null,
  source_id integer references public.sources(id) on delete set null,
  query_run_id bigint references public.query_runs(id) on delete set null,
  provider_item_id text,
  title text not null,
  description text,
  author text,
  source_name text,
  source_domain text,
  aggregator_url text,
  original_url text,
  canonical_url text,
  image_url text,
  published_at timestamptz,
  published_date_source text check (published_date_source in ('rss','provider','page_metadata','page','unconfirmed')),
  published_date_confirmed boolean not null default false,
  captured_at timestamptz not null default now(),
  raw_payload jsonb not null default '{}'::jsonb,
  content_hash text not null,
  processing_status text not null default 'pending' check (processing_status in ('pending','classified','review','discarded','error')),
  processing_error text,
  unique(provider, content_hash)
);

alter table public.news add column if not exists candidate_id bigint references public.candidate_news(id) on delete set null;
alter table public.news add column if not exists aggregator_url text;
alter table public.news add column if not exists original_url text;
alter table public.news add column if not exists author text;
alter table public.news add column if not exists published_date_source text;
alter table public.news add column if not exists published_date_confirmed boolean not null default false;
alter table public.news add column if not exists captured_at timestamptz not null default now();
alter table public.news add column if not exists provider text;

create table if not exists public.news_query_matches (
  news_id bigint not null references public.news(id) on delete cascade,
  search_query_id bigint not null references public.search_queries(id) on delete cascade,
  query_run_id bigint references public.query_runs(id) on delete set null,
  matched_at timestamptz not null default now(),
  primary key(news_id, search_query_id)
);

create table if not exists public.monitor_locks (
  lock_name text primary key,
  owner_token uuid not null,
  acquired_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index if not exists idx_candidate_captured on public.candidate_news(captured_at desc);
create index if not exists idx_candidate_published on public.candidate_news(published_at desc nulls last);
create index if not exists idx_candidate_canonical on public.candidate_news(canonical_url);
create index if not exists idx_monitor_runs_started on public.monitor_runs(started_at desc);
create index if not exists idx_query_runs_monitor on public.query_runs(monitor_run_id, started_at);
create index if not exists idx_news_published_tz on public.news(published_at desc nulls last);

